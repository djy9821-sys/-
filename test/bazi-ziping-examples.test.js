const FAMILY = {
  正官格: '论正官', 正财格: '论财', 偏财格: '论财', 正印格: '论印绶', 偏印格: '论印绶', 食神格: '论食神',
  七杀格: '论偏官', 伤官格: '论伤官', 羊刃格: '论阳刃', 建禄格: '论建禄月劫', 月劫格: '论建禄月劫',
};
const chapterOf = (patternName) => FAMILY[String(patternName ?? '').replace(/^杂气/, '')] ?? null;

const patternOf = ([, , , pillars, [year, month, day, hourIndex]]) => {
  const chart = buildBaziChart({ calendarType: 'solar', year, month, day, hourIndex, gender: 'male' });
  assert.equal(chart.pillars.map(({ ganZhi }) => ganZhi).join(' '), pillars, `${pillars} 的日期取错了`);
  return judgeBaziPattern(chart, analyzeStrength(chart)).pattern;
};

test('《子平真诠》八格各论命例：程序取格与命例所在章节一致（已知例外逐条说明）', () => {
  const mismatched = [];
  EXAMPLES.forEach((example) => {
    const [id, chapter, name, pillars, , exceptionPattern] = example;
    const pattern = patternOf(example);
    if (exceptionPattern) {
      // 例外条目锁定当前结果：取格逻辑改动后要重新对照原文，确认是否已与原书一致。
      assert.equal(pattern.name.replace(/^杂气/, ''), exceptionPattern, `${id} ${name}（${pillars}）的例外结果变了`);
      return;
    }
    if (chapterOf(pattern.name) !== chapter) mismatched.push(`${id} ${name}（${pillars}）：书在${chapter}，程序取${pattern.name}`);
  });
  assert.deepEqual(mismatched, []);
  assert.ok(EXAMPLES.length >= 78);
  assert.equal(EXAMPLES.filter((example) => example[5]).length, 4);
});

test('《子平真诠》取格细则在原书命例上的体现', () => {
  const byPillars = (pillars) => patternOf(EXAMPLES.find((example) => example[3] === pillars));
  // 论用神变化·其五：乙生申月透壬化印而又透戊，财能生官，印逢财而退位，格成正官（薛相公命）。
  assert.match(byPillars('甲申 壬申 乙巳 戊寅').basis, /化神退位，仍以本气庚（正官）为格/);
  // 「甲透未库」：辛生未月，甲以同类透出论财（汪学士命）。
  const kuCai = byPillars('甲子 辛未 辛酉 壬辰');
  assert.equal(kuCai.name, '杂气正财格');
  assert.match(kuCai.basis, /为木库，库中乙以同类透出论/);
  // 「透干会支，取其清者用之」：戊生未月，乙透而卯未会木，取官不取印。
  const guan = byPillars('壬戌 丁未 戊申 乙卯');
  assert.equal(guan.name, '杂气正官格');
  assert.match(guan.basis, /透而又会支/);
  // 申中不论戊：马参政命壬生申月透戊，书作印格（身重印轻）。
  assert.equal(byPillars('壬寅 戊申 壬辰 壬寅').name, '偏印格');
});
